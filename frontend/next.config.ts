import type { NextConfig } from "next";

// The browser only ever talks to this Next.js origin. API calls under /api are
// proxied to the FastAPI backend, so the backend URL, credentials and any future
// session cookies stay same-origin and are never exposed to client-side code.
const BACKEND_URL = process.env.BACKEND_URL ?? "http://localhost:8000";

const nextConfig: NextConfig = {
  cacheComponents: true,
  partialPrefetching: true,
  poweredByHeader: false,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  async rewrites() {
    return [{ source: "/api/:path*", destination: `${BACKEND_URL}/api/:path*` }];
  },
};

export default nextConfig;
